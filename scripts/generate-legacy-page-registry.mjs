#!/usr/bin/env node
import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const pagesDir = path.join(root, "pages");
const outputDir = path.join(root, "src", "generated");
const pages = [];
const layouts = [];

async function walk(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      await walk(absolute);
      continue;
    }
    if (!entry.isFile() || !/\.tsx$/.test(entry.name)) continue;
    const relative = path.relative(root, absolute).split(path.sep).join("/");

    // /store/{slug} was an old public route and is not part of Oni247's URL
    // contract. pages/store.$slug.tsx remains a shared component imported by
    // pages/$slug.tsx; none of the old store.$slug.* files are routes.
    if (relative.startsWith("pages/store.$slug")) continue;

    if (relative.endsWith(".pageLayout.tsx")) layouts.push(relative);
    else pages.push(relative);
  }
}

await walk(pagesDir);
pages.sort();
layouts.sort();

// Keep generated dynamic imports extensionless so TypeScript Bundler resolution\n// and Next.js resolve the source .tsx modules without TS5097.\nconst importPath = (file) => "../../" + file.replace(/\.tsx$/, "");
const pageEntries = pages.map((file) =>
  `  ${JSON.stringify("../" + file)}: () => import(${JSON.stringify(importPath(file))}),`,
).join("\n");
const layoutEntries = layouts.map((file) =>
  `  ${JSON.stringify("../" + file)}: () => import(${JSON.stringify(importPath(file))}),`,
).join("\n");

const source = `// Generated by scripts/generate-legacy-page-registry.mjs. Do not edit by hand.
import type React from "react";

type PageModule = { default: React.ComponentType };
type LayoutModule = { default: React.ComponentType<{ children: React.ReactNode }>[] };

export const pageModules: Record<string, () => Promise<PageModule>> = {
${pageEntries}
};

export const layoutModules: Record<string, () => Promise<LayoutModule>> = {
${layoutEntries}
};
`;

await mkdir(outputDir, { recursive: true });
await writeFile(path.join(outputDir, "legacyPageRegistry.ts"), source, "utf8");
console.info(`[oni247] Generated legacy compatibility registry: ${pages.length} pages, ${layouts.length} layouts.`);
